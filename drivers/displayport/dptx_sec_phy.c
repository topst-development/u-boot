static void dptx_reset_sec_phy(struct Dptx_Params *pstDptx)
{
	uint32_t reg_wval;

	if (pstDptx->ePhy_Dev == PHY_DEVICE_SEC) {
		reg_wval = ((uint32_t)PHY_CLK_DIV_DISABLE | (uint32_t)LC_REF_RO_PLL);
		(void)Dptx_Cfg_Set_PHY_Cfg(pstDptx, reg_wval);

		reg_wval = ((uint32_t)CFG_LANE_RESET | (uint32_t)CFG_CMN_RESET
			  | (uint32_t)CFG_INT_RESET);
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);

		reg_wval |= (uint32_t)CFG_DP_PHY_APB_RESET;
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);
		udelay(1);

		reg_wval &= ~(uint32_t)CFG_DP_PHY_APB_RESET;
		(void)Dptx_Cfg_SoftReset(pstDptx, reg_wval);
	}
}

static int32_t dptx_sec_check_phy_ssc_reg_value(uint8_t link_rate, uint32_t reg_addr,
						uint32_t *reg_val)
{
	int32_t ret = DPTX_RETURN_NO_ERROR;
	uint32_t reg_overrid_val = 0u;

	if (reg_val == NULL) {
		ret = -DPTX_RETURN_EINVAL;
		dptx_err("reg_val is NULL");
	} else {
		reg_overrid_val = *reg_val;
		/* HBR3 ------------------------------------------------------*/
		if (link_rate == (uint8_t)LINK_RATE_HBR3) {
			if (reg_addr == (uint32_t)SEC_PHY_REG0030) {
				/* To disable spread spectrum clocking, set lcpll_ssc_en to 0 */
				reg_overrid_val &= ~((uint32_t)1u << 0);
			}
			if (reg_addr == (uint32_t)SEC_PHY_REG0031) {
				/* To disable spread spectrum clocking, set lcpll_ssc_fm_deviation to 0x20 */
				reg_overrid_val = SEC_PHY_REG0031_RESET;
			}
			if (reg_addr == (uint32_t)SEC_PHY_REG0032) {
				/* To disable spread spectrum clocking, set lcpll_ssc_fm_freq to 0xC */
				reg_overrid_val = SEC_PHY_REG0032_HBR3_SSC_DIS;
			}
		} else {
			/* link rate below HBR3 --------------------------------------*/
			if (reg_addr == (uint32_t)SEC_PHY_REG0074) {
				/* To disable spread spectrum clocking, set ropll_ssc_en to 0 */
				reg_overrid_val &= ~((uint32_t)1u << 0);
			}
			if (reg_addr == (uint32_t)SEC_PHY_REG0075) {
				/* To disable spread spectrum clocking, set ropll_ssc_fm_deviation to 0x20 */
				reg_overrid_val = SEC_PHY_REG0075_RESET;
			}
			if (reg_addr == (uint32_t)SEC_PHY_REG0076) {
				/* To disable spread spectrum clocking, set ropll_ssc_fm_freq to 0xc */
				reg_overrid_val = SEC_PHY_REG0076_RESET;
			}
		}
		/* Common ----------------------------------------------------*/
		if (reg_addr == (uint32_t)SEC_PHY_REG0099) {
			if (reg_overrid_val == (uint32_t)SEC_PHY_REG0099_RBR_SC_EN) {
				/* RBR, HBR and HBR2 are same value */
				reg_overrid_val = (uint32_t)SEC_PHY_REG0099_RBR_SSC_DIS;
			}
			if (reg_overrid_val == (uint32_t)SEC_PHY_REG0099_HBR3_SC_EN) {
				reg_overrid_val = (uint32_t)SEC_PHY_REG0099_HBR3_SSC_DIS;
			}
		}
		if (reg_addr == (uint32_t)SEC_PHY_REG0047) {
			/* To disable spread spectrum clocking, set ropll_ssc_en to 0 */
			reg_overrid_val &= ~((uint32_t)1u << 0);
		}
		*reg_val = reg_overrid_val;
	}
	return ret;
}

int32_t Dptx_Sec_PHY_Init(struct Dptx_Params *pstDptx, uint8_t ucLinkRate, uint8_t ucLanes)
{
	bool bOffsetInRange, bPll_Ready, bPhy_Ready;
	uint8_t uclink_rate;
	int32_t iRetVal = DPTX_RETURN_NO_ERROR;
	uint32_t uiElements, uiPhy_Cfg;
	uint32_t uiReg_Addr, uiReg_Offset, uiReg_W_data;
	const struct SEC_PHY_Reg_Data *pstLink_Reg_Data;
	const struct SEC_PHY_Reg_Data *pstAux_Reg_Data;
	const struct SEC_PHY_Reg_Data *pstSB_Reg_Data;

	if (pstDptx->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_dbg("It's valid for SEC Phy only.. phy type = %d", pstDptx->ePhy_Dev);

		iRetVal = DPTX_RETURN_NO_ERROR;
	} else {
		dptx_reset_sec_phy(pstDptx);

		bOffsetInRange = CHECK_REG_OFFSET(pstDptx->uiSEC_PHY_Reg_Offset);
		if (!bOffsetInRange) {
			dptx_err("Invalid reg offset as 0x%x", pstDptx->uiRegBank_RegAddr_Offset);

			iRetVal = DPTX_RETURN_EINVAL;
		}

		if (iRetVal == DPTX_RETURN_NO_ERROR) {
			dptx_info("Init SEC Phy with Max rate(%u) = %s",
						ucLinkRate,
						(ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_RBR) ? "RBR" :
						(ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR) ? "HBR" :
						(ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR2) ? "HBR2" : "HBR3");

			uiReg_Offset = pstDptx->uiSEC_PHY_Reg_Offset;

			pstLink_Reg_Data = stSEC_PHY_Link_Reg_Data;

			/* Set LC (cascade) or RO PLL */
			uiPhy_Cfg = (ucLinkRate == (uint8_t)DPTX_PHYIF_CTRL_RATE_HBR3) ?
				    (uint32_t)((uint32_t)PHY_CLK_DIV_DISABLE | RO_REF_RO_PLL) :
				    (uint32_t)((uint32_t)PHY_CLK_DIV_DISABLE | LC_REF_RO_PLL);
			iRetVal = Dptx_Cfg_Set_PHY_Cfg(pstDptx, uiPhy_Cfg);

			for (uiElements = 0; (pstLink_Reg_Data[uiElements].uireg_add != (uint32_t)SEC_PHY_REG_MAX); uiElements++) {

				uclink_rate = pstLink_Reg_Data[uiElements].uclink_rate;

				if ((uclink_rate != (uint8_t)LINK_RATE_MAX) && (uclink_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}

				if (pstLink_Reg_Data[uiElements].uireg_add == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(pstLink_Reg_Data[uiElements].uireg_val);
					continue;
				}

				//dptx_info("Reg[0x%x] = 0x%x", pstLink_Reg_Data[uiElements].uireg_add, pstLink_Reg_Data[uiElements].uireg_val);

				uiReg_W_data = pstLink_Reg_Data[uiElements].uireg_val;
				uiReg_Addr = pstLink_Reg_Data[uiElements].uireg_add;

				if (DPTX_RETURN_ERROR(dptx_sec_check_phy_ssc_reg_value(ucLinkRate,
										       uiReg_Addr, &uiReg_W_data))) {
					break;
				}
				Dptx_Reg_Writel(pstDptx, (uiReg_Offset + uiReg_Addr), uiReg_W_data);
			}

			/* enable PHY_BIAS and PHY_BGR */
			uiPhy_Cfg |= (uint32_t)((uint32_t)CFG_BIAS_EN | CFG_BGR_EN);
			iRetVal = Dptx_Cfg_Set_PHY_Cfg(pstDptx, uiPhy_Cfg);
			udelay(10);

			pstAux_Reg_Data = stSEC_PHY_Aux_Reg_Data;

			for (uiElements = 0; (pstAux_Reg_Data[uiElements].uireg_add != (uint32_t)SEC_PHY_REG_MAX); uiElements++) {

				uclink_rate = pstAux_Reg_Data[uiElements].uclink_rate;

				if ((uclink_rate != (uint8_t)LINK_RATE_MAX) && (uclink_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}

				if (pstAux_Reg_Data[uiElements].uireg_add == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(pstAux_Reg_Data[uiElements].uireg_val);
					continue;
				}

		//		dptx_info("Reg[0x%x] = 0x%x", pstAux_Reg_Data[uiElements].uireg_add, pstAux_Reg_Data[uiElements].uireg_val);

				uiReg_W_data = pstAux_Reg_Data[uiElements].uireg_val;
				uiReg_Addr = pstAux_Reg_Data[uiElements].uireg_add;

				Dptx_Reg_Writel(pstDptx, (uiReg_Offset + uiReg_Addr), uiReg_W_data);
			}

			/* release PHY_INIT_reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)(CFG_LANE_RESET | CFG_CMN_RESET | CFG_DP_MB_RESET));
			udelay(10);

			/* enable PHY_PLL */
			uiPhy_Cfg |= (uint32_t)CFG_PLL_EN;
			iRetVal = Dptx_Cfg_Set_PHY_Cfg(pstDptx, uiPhy_Cfg);
			udelay(10);

			/* release PHY_CMN reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)(CFG_LANE_RESET | CFG_DP_MB_RESET));

			/* wait o_pll_lock_done and o_pll_clk_rdy */
			iRetVal = Dptx_Cfg_Check_PHY_Pll(pstDptx, &bPll_Ready);
		}

		if (iRetVal == DPTX_RETURN_NO_ERROR) {
			udelay(10);

			/* release PHY_lane_reset */
			(void)Dptx_Cfg_SoftReset(pstDptx, (uint32_t)CFG_DP_MB_RESET);

			/* wait o_phy_rdy */
			iRetVal = Dptx_Cfg_Check_PHY_Ready(pstDptx, &bPhy_Ready);
		}

		if (iRetVal == DPTX_RETURN_NO_ERROR) {
			pstSB_Reg_Data = stSEC_PHY_SB_Reg_Data;

			for (uiElements = 0; (pstSB_Reg_Data[uiElements].uireg_add != (uint32_t)SEC_PHY_REG_MAX); uiElements++) {

				uclink_rate = pstSB_Reg_Data[uiElements].uclink_rate;

				if ((uclink_rate != (uint8_t)LINK_RATE_MAX) && (uclink_rate != ucLinkRate)) {
					/*For KCS */
					continue;
				}

				if (pstSB_Reg_Data[uiElements].uireg_add == (uint32_t)SEC_PHY_DELAY_USEC_REG) {
					udelay(pstSB_Reg_Data[uiElements].uireg_val);
		//			dptx_info(" 0x%x : %u", pstSB_Reg_Data[uiElements].uireg_add, pstSB_Reg_Data[uiElements].uireg_val);
					continue;
				}

		//		dptx_info("Reg[0x%x] = 0x%x", pstSB_Reg_Data[uiElements].uireg_add, pstSB_Reg_Data[uiElements].uireg_val);

				uiReg_W_data = pstSB_Reg_Data[uiElements].uireg_val;
				uiReg_Addr = pstSB_Reg_Data[uiElements].uireg_add;

				if (pstSB_Reg_Data[uiElements].uireg_add == (uint32_t)SEC_PHY_REG0108) {
					uiReg_W_data &= ~((uint32_t)3u << 4);
					uiReg_W_data |= ((pstDptx->hw_config.aux_hysteresis & 0x3u) << 4);
				}

				Dptx_Reg_Writel(pstDptx, (uiReg_Offset + uiReg_Addr), uiReg_W_data);
			}

			iRetVal = Dptx_Cfg_Check_Sec_PHY_SB_Ready(pstDptx, &bPhy_Ready);
		}

		if (iRetVal == DPTX_RETURN_NO_ERROR) {

			iRetVal = Dptx_Sec_Set_NumOfLanes(pstDptx, ucLanes);

			for (uiElements = 0; uiElements < ucLanes; uiElements++) {
				(void)dptx_sec_set_phy_sigan_quality(pstDptx, uiElements, ucLinkRate,
						 VOLTAGE_SWING_LEVEL_0, PRE_EMPHASIS_LEVEL_0);
			}
		}
	}

	return iRetVal;
}

int32_t Dptx_Sec_Set_NumOfLanes(struct Dptx_Params *pstDptx, uint8_t ucLanes)
{
	bool bOffsetInRange;
	uint32_t uiReg_Addr, uiReg_Offset, uiReg_W_data;
	int32_t iRetVal = DPTX_RETURN_NO_ERROR;
	bool internal_ok = (bool)true;

	if (pstDptx->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_dbg("Nothing to do not for Samsung PHY");
		internal_ok = (bool)false;
	}

	if (internal_ok) {
		bOffsetInRange = CHECK_REG_OFFSET(pstDptx->uiSEC_PHY_Reg_Offset);
		if (!bOffsetInRange) {
			dptx_err("Invalid reg offset as 0x%x", pstDptx->uiRegBank_RegAddr_Offset);
			iRetVal = DPTX_RETURN_EINVAL;
			internal_ok = (bool)false;
		}
	}

	if (internal_ok) {
		uiReg_Offset = pstDptx->uiSEC_PHY_Reg_Offset;
		uiReg_Addr = (uint32_t)SEC_PHY_REG0207;

		switch (ucLanes) {
		case 1u:
			uiReg_W_data = 0x01U;
			break;
		case 2u:
			uiReg_W_data = 0x03U;
			break;
		case 4u:
			uiReg_W_data = 0x0FU;
			break;
		default:
			dptx_err("Invalid Num of lanes as 0x%x", ucLanes);
			iRetVal = DPTX_RETURN_EINVAL;
			internal_ok = (bool)false;
			break;
		}
	}

	if (internal_ok) {
		Dptx_Reg_Writel(pstDptx, (uiReg_Offset + uiReg_Addr), uiReg_W_data);
	}
	return iRetVal;
}

uint32_t dptx_sec_get_main_equalization(struct Dptx_Params *dptx_params, uint8_t lane_idx)
{
	uint32_t reg_offset, reg_addr;
	uint32_t reg_val = 0u;

	if (dptx_params->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (lane_idx > (uint8_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
		} else {
			if (!CHECK_REG_OFFSET(dptx_params->uiSEC_PHY_Reg_Offset)) {
				dptx_err("Invalid reg addr as 0x%x",
				     dptx_params->uiRegBank_RegAddr_Offset);
			} else if (!CHECK_REG_OFFSET(dptx_sec_main_reg_offset_table[lane_idx])) {
				dptx_err("Invalid reg offset as 0x%x",
				     dptx_sec_main_reg_offset_table[lane_idx]);
			} else {
				reg_addr = dptx_params->uiSEC_PHY_Reg_Offset;
				reg_offset = dptx_sec_main_reg_offset_table[lane_idx];

				reg_val = Dptx_Reg_Readl(dptx_params, (reg_addr +  reg_offset));
				reg_val &= 0x1Fu;
			}
		}
	}
	return reg_val;
}

int32_t dptx_sec_set_main_equalization(struct Dptx_Params *dptx_params, uint32_t lane_idx, uint32_t eq_val)
{
	uint32_t reg_offset, reg_addr, reg_val;
	int32_t ret = DPTX_RETURN_NO_ERROR;

	if (dptx_params->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (eq_val > 13u) {  /* 0 to 14 */
			dptx_err("Invalid VSW as %u", eq_val);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (lane_idx > (uint8_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			if (!CHECK_REG_OFFSET(dptx_params->uiSEC_PHY_Reg_Offset)) {
				dptx_err("Invalid reg addr as 0x%x",
				     dptx_params->uiSEC_PHY_Reg_Offset);

				ret = -DPTX_RETURN_EINVAL;
			} else if (!CHECK_REG_OFFSET(dptx_sec_main_reg_offset_table[lane_idx])) {
				dptx_err("Invalid reg offset as 0x%x",
				     dptx_sec_main_reg_offset_table[lane_idx]);

				ret = -DPTX_RETURN_EINVAL;
			} else {
				reg_addr = dptx_params->uiSEC_PHY_Reg_Offset;
				reg_offset = dptx_sec_main_reg_offset_table[lane_idx];

				reg_val = (uint32_t)1u << 5; /* enable overrid */
				reg_val |= (eq_val & 0x1Fu);

				Dptx_Reg_Writel(dptx_params, (reg_addr +  reg_offset), reg_val);
			}
		}
	}
	return ret;
}

