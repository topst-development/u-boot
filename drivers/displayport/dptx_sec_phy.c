int32_t dptx_sec_set_post_equalization(struct Dptx_Params *dptx_params, uint32_t lane_idx, uint32_t eq_val)
{
	int32_t ret = DPTX_RETURN_NO_ERROR;
	uint32_t reg_offset, reg_addr, reg_val;

	if (dptx_params->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (eq_val > 15u) { /* 0 to 14 */
			dptx_err("Invalid VSW as %u", eq_val);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (lane_idx > (uint32_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			if (!CHECK_REG_OFFSET(dptx_params->uiSEC_PHY_Reg_Offset)) {
				dptx_err("Invalid reg addr as 0x%x",
					dptx_params->uiRegBank_RegAddr_Offset);

				ret = -DPTX_RETURN_EINVAL;
			} else if (!CHECK_REG_OFFSET(dptx_sec_post_reg_offset_table[lane_idx])) {
				dptx_err("Invalid reg offset as 0x%x",
					dptx_sec_post_reg_offset_table[lane_idx]);

				ret = -DPTX_RETURN_EINVAL;
			} else {
				reg_addr = dptx_params->uiSEC_PHY_Reg_Offset;
				reg_offset = dptx_sec_post_reg_offset_table[lane_idx];

				reg_val = (uint32_t)1u << 4; /* enable overrid */
				reg_val |= (eq_val & 0xFu);

				Dptx_Reg_Writel(dptx_params, (reg_addr +  reg_offset), reg_val);
			}
		}
	}
	return ret;
}

int32_t dptx_sec_set_phy_sigan_quality(struct Dptx_Params *dev_param,
				       uint32_t lane_idx,
				       uint8_t link_rate,
				       enum PHY_VOLTAGE_SWING_LEVEL voltage_swing,
				       enum PHY_PRE_EMPHASIS_LEVEL pre_emphasis)
{
	int32_t ret = DPTX_RETURN_NO_ERROR;
	uint32_t linear_idx;

	if (dev_param->ePhy_Dev != PHY_DEVICE_SEC) {
		dptx_debug("Nothing to do not for Samsung PHY");
	} else {
		if (voltage_swing >= VOLTAGE_SWING_LEVEL_MAX) {
			dptx_err("Invalid VSW as %u", voltage_swing);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (pre_emphasis >= PRE_EMPHASIS_LEVEL_MAX) {
			dptx_err("Invalid Pre-emp as %u", pre_emphasis);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (lane_idx > (uint32_t)PHY_LANE_3) {
			dptx_err("Invalid lane idx as %u", lane_idx);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (link_rate > (uint8_t)LINK_RATE_HBR3) {
			dptx_err("Invalid link rate as %u", link_rate);
			ret = -DPTX_RETURN_EINVAL;
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			linear_idx = ((uint32_t)voltage_swing * 4u) + (uint32_t)pre_emphasis;

			if ((linear_idx == 7u) || (linear_idx == 10u) ||
			    (linear_idx == 11u) || (linear_idx == 13u) ||
			    (linear_idx == 14u) || (linear_idx == 15u) ||
			    (linear_idx >= 16u)) {
				/**
				 * These values represent combinations of Voltage Swing (VSW)
				 * and Pre-Emphasis (PRE) that are invalid according to
				 * DisplayPor specifications.
				 *
				 * The array layout represents the following combinations:
				 *
				 * - VSW 0 PRE 0, VSW 0 PRE 1, ..., VSW 0 PRE 3
				 * - VSW 1 PRE 0, VSW 1 PRE 1, ..., VSW 1 PRE 3
				 * - ...
				 * - VSW 3 PRE 0, VSW 3 PRE 1, ..., VSW 3 PRE 3
				 *
				 * The loop index sequentially maps to these combinations.
				 * Invalid EQ configurations are as follows:
				 * - Index 7  (VSW 1 PRE 3)
				 * - Index 10 (VSW 2 PRE 2)
				 * - Index 11 (VSW 2 PRE 3)
				 * - Index 13 (VSW 3 PRE 1)
				 * - Index 14 (VSW 3 PRE 2)
				 * - Index 15 (VSW 3 PRE 3)
				 */
				dptx_err("Not allowed voltage swing %u level and pre-emphsis %u level", voltage_swing, pre_emphasis);
				ret = -DPTX_RETURN_EINVAL;
			}
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			ret = dptx_sec_set_main_equalization(dev_param, lane_idx,
					dev_param->hw_config.phy_eq[link_rate].main_eq[linear_idx]);
		}
		if (DPTX_RETURN_SUCCESS(ret)) {
			ret = dptx_sec_set_post_equalization(dev_param, lane_idx,
					dev_param->hw_config.phy_eq[link_rate].post_eq[linear_idx]);
		}
	}
	return ret;
}

